#!/usr/bin/env bash
# Dev server for one feature-branch worktree, on a fixed port (default :8888).
#
# The old dev server ran from the dev checkout root, whose .env sets no
# MUSCAT_DB_PATH, so `serve` fell back to ./muscat.db -- the production
# database -- and wrote to the production obslog. This script instead runs a
# worktree against the staging data set (the same DB, obslog and output dirs
# staging on :8003 uses), never anything production owns.
#
# Usage:  deploy/dev-server.sh start  [--port N] [WORKTREE]   # default: worktree holding cwd
#         deploy/dev-server.sh stop   [--port N]
#         deploy/dev-server.sh status [--port N]
#
# --port (-p) defaults to 8888. Every server runs in tmux session muscatdb-dev,
# in a window named port-<N> (attach: tmux attach -t muscatdb-dev), so two
# worktrees can run side by side without one start killing the other's window. The production and
# staging ports (8000-8003) are refused outright: `stop` would otherwise find
# production's muscat-db on :8001 and kill it as if it were a dev server.
#
# Typical flow for a new feature:
#   git worktree add -b feat/123-thing ~/temp/wt-123-thing origin/test
#   deploy/dev-server.sh start ~/temp/wt-123-thing
#
# How it works: the worktree gets a generated, gitignored .env -- staging's
# .env (so the dev server behaves like staging) followed by
# dev overrides. muscat_db/__init__.py loads it via find_dotenv(usecwd=True), so
# no setting or secret has to go on the tmux command line. One dev server runs
# per port: starting another worktree on the same port replaces the one there.
#
# Data is shared, only code is per worktree: the DB, obslog and prose/timer/
# harmonic output dirs all come from staging (STAGING_ROOT), never from the
# worktree, so every worktree and :8003 see the same data set. This is
# deliberate (see the dev-server bullet in AGENTS.md): the DB is staging's live
# muscat_test.db, so writes made here are visible on :8003 and are wiped by the
# nightly re-seed from production.
#
# Production guard: `start` resolves each of those paths with realpath and
# refuses to go on if one is inside the dev checkout, the production deploy
# checkout, production's obslog or production's output tree, or is production's
# DB. STAGING_ROOT and STAGING_ENV are overridable, so a mistyped value would
# otherwise point the dev server (and its obslog writes) at production.
#
# Security: there is no nginx in front, so MUSCAT_REQUIRE_AUTH is 0 and every
# request is anonymous. Anonymous means the `everyone` grant only -- restricted
# proposals stay hidden, /api/admin refuses, and a forged X-Forwarded-User is
# ignored because the proxy secret still validates -- but loopback is reachable
# by every account on this host, so any of them can read the unrestricted data
# and act anonymously. That matches the old dev server; closing it needs an
# nginx Basic Auth block like staging's. The bind is loopback only, enforced.
#
# Environment overrides:
#   DEV_HOST (127.0.0.1)
#   DEV_MAX_FULL_JOBS (0, as staging)  STAGING_ENV  STAGING_ROOT  DEV_CHECKOUT
#   UV_BIN (default: `uv` on PATH, then ~/.local/bin/uv)  EXT_TOOLS
#   PROD_ROOT  PROD_DB  PROD_OBSLOG_DIR  PROD_OUTPUT_ROOT   (production guard)

set -euo pipefail

DEFAULT_PORT=8888
RESERVED_PORTS="8000 8001 8002 8003"   # nginx/uvicorn for production and staging
PORT="$DEFAULT_PORT"
HOST="${DEV_HOST:-127.0.0.1}"
STAGING_ROOT="${STAGING_ROOT:-$HOME/deploy/test}"
STAGING_ENV="${STAGING_ENV:-$STAGING_ROOT/app/.env}"
DEV_CHECKOUT="${DEV_CHECKOUT:-$HOME/github/research/project/muscat-db}"
EXT_TOOLS="${EXT_TOOLS:-$HOME/github/research/project/ext_tools}"
# What a dev server must never write to (see notes/DEPLOYMENT.md, environments
# table). The production DB lives in the dev checkout, so DEV_CHECKOUT already
# covers it; PROD_DB is listed separately in case it is moved.
PROD_ROOT="${PROD_ROOT:-$HOME/deploy/main}"
PROD_DB="${PROD_DB:-$DEV_CHECKOUT/muscat.db}"
PROD_OBSLOG_DIR="${PROD_OBSLOG_DIR:-/ut2/muscat/obslog}"
PROD_OUTPUT_ROOT="${PROD_OUTPUT_ROOT:-$HOME/ql}"   # prose/timer/harmonic outputs
HEALTH_TIMEOUT_S="${DEV_HEALTH_TIMEOUT_S:-300}"   # first start runs `uv sync`
ENV_MARKER="# generated by deploy/dev-server.sh -- do not edit, rerun the script"

die() { echo "dev-server: $*" >&2; exit 1; }

usage() {
  echo "usage: $0 {start [--port N] [WORKTREE]|stop [--port N]|status [--port N]}  (port default $DEFAULT_PORT)" >&2
  exit 2
}

listener_pids() {
  # `|| true`: an empty port makes grep exit 1, which pipefail + set -e would
  # turn into a silent exit of the whole script.
  { ss -ltnpH "sport = :$PORT" 2>/dev/null | grep -o 'pid=[0-9]*' | cut -d= -f2 | sort -u; } || true
}

# Print the muscat-db server process that owns pid (pid itself or its nearest
# muscat-db ancestor); fail if there is none. Under --reload the socket is held
# by uvicorn's multiprocessing child, whose own cmdline is a bare
# `python -c "from multiprocessing.spawn ..."`, and signalling only that child
# would let the reloader parent respawn it.
#
# The match is on argv, not a substring of the joined cmdline: the repo path
# itself contains "muscat-db", so a substring test would claim e.g. a Jupyter
# started from .../muscat-db/notebooks (or the shell that launched it).
muscat_server_of() {
  local pid="$1" i
  local -a argv
  while [ -n "$pid" ] && [ "$pid" -gt 1 ]; do
    mapfile -d '' -t argv < "/proc/$pid/cmdline" 2>/dev/null || argv=()
    for ((i = 0; i + 1 < ${#argv[@]}; i++)); do
      if [ "${argv[i]##*/}" = muscat-db ] && [[ "${argv[i+1]}" =~ ^(serve|restart)$ ]]; then
        echo "$pid"
        return 0
      fi
    done
    pid="$(awk '/^PPid:/ {print $2}' "/proc/$pid/status" 2>/dev/null || true)"
  done
  return 1
}

pid_uid() { awk '/^Uid:/ {print $2}' "/proc/$1/status" 2>/dev/null; }

# Refuse to signal anything on the port that is not our own muscat-db server:
# whatever else holds it -- another program, or another user's server, which
# kill could not signal anyway -- is not ours to stop.
stop_server() {
  local pids pid owner owners=""
  pids="$(listener_pids)"
  [ -n "$pids" ] || { echo "no server on :$PORT"; return 0; }
  for pid in $pids; do
    owner="$(muscat_server_of "$pid")" \
      || die "pid $pid on :$PORT is not a muscat-db server; not touching it"
    [ "$(pid_uid "$owner")" = "$(id -u)" ] \
      || die "the muscat-db server on :$PORT (pid $owner) belongs to another user; pick another --port"
    owners+=" $owner"
  done
  echo "stopping :$PORT (pid$owners)"
  kill $owners $pids 2>/dev/null || true
  for _ in $(seq 25); do
    [ -z "$(listener_pids)" ] && return 0
    sleep 0.2
  done
  kill -9 $(listener_pids) 2>/dev/null || true
}

status() {
  local pid
  pid="$(listener_pids | head -1)"
  if [ -z "$pid" ]; then
    echo ":$PORT -- not running"
    return 1
  fi
  local cwd
  cwd="$(readlink "/proc/$pid/cwd")"
  echo ":$PORT -- pid $pid, cwd $cwd"
  # The DB path is set in-process from .env, so /proc/<pid>/environ never has it.
  grep '^MUSCAT_DB_PATH=' "$cwd/.env" 2>/dev/null | tail -1 || true
  curl -fsS -m 5 -o /dev/null -w "healthz %{http_code}\n" "http://127.0.0.1:$PORT/healthz" || true
}

resolve_worktree() {
  local wt
  wt="$(git -C "${1:-.}" rev-parse --show-toplevel 2>/dev/null)" \
    || die "${1:-.} is not inside a git worktree"
  [ -f "$wt/src/muscat_db/__init__.py" ] || die "$wt is not a muscat-db worktree"
  # The dev checkout's own .env points at production paths; generating a .env
  # there would overwrite it. Feature work belongs in a separate worktree.
  [ "$(realpath "$wt")" != "$(realpath "$DEV_CHECKOUT")" ] \
    || die "refusing the dev checkout itself; use: git worktree add -b <branch> ~/temp/wt-<name> origin/test"
  echo "$wt"
}

# Catalog CSVs and other data files are gitignored, so a fresh worktree has
# none. Link the dev checkout's copies in (read-only reference data), never
# replacing a file the worktree already has.
link_data_files() {
  local wt="$1" rel
  while IFS= read -r rel; do
    [ -e "$wt/$rel" ] && continue
    mkdir -p "$(dirname "$wt/$rel")"
    ln -s "$DEV_CHECKOUT/$rel" "$wt/$rel"
  done < <(git -C "$DEV_CHECKOUT" ls-files --others --ignored --exclude-standard data/)
}

# uv: $UV_BIN, else whatever is on PATH, else ~/.local/bin/uv. Looked up in
# `start` only, so `stop` and `status` do not need it.
find_uv() {
  local uv="${UV_BIN:-}"
  [ -n "$uv" ] || uv="$(command -v uv || true)"
  [ -n "$uv" ] || { [ ! -x "$HOME/.local/bin/uv" ] || uv="$HOME/.local/bin/uv"; }
  [ -n "$uv" ] && [ -x "$uv" ] || die "uv not found; put it on PATH or set UV_BIN"
  echo "$uv"
}

# True if $1 is $2 or inside it, comparing resolved paths. realpath -m so a
# path that does not exist yet still resolves; symlinks that do exist are
# followed, so a link into production cannot hide it.
path_within() {
  local p c
  p="$(realpath -m -- "$1")"
  c="$(realpath -m -- "$2")"
  [ "$p" = "$c" ] || [[ "$p" == "$c"/* ]]
}

refuse_prod_path() {
  local label="$1" path="$2" prod
  for prod in "$DEV_CHECKOUT" "$PROD_ROOT" "$PROD_DB" "$PROD_OBSLOG_DIR" "$PROD_OUTPUT_ROOT"; do
    if path_within "$path" "$prod"; then
      die "$label resolves to $path, inside production ($prod); check STAGING_ROOT=$STAGING_ROOT"
    fi
  done
}

# The data set the dev server uses, resolved once. write_env and the launch
# line use these same values, so what is checked is what is written.
resolve_staging_paths() {
  SP_DB_PATH="$(realpath -m -- "$STAGING_ROOT/muscat_test.db")"
  SP_OBSLOG_DIR="$(realpath -m -- "$STAGING_ROOT/obslog")"
  SP_PROSE_DIR="$(realpath -m -- "$STAGING_ROOT/prose")"
  SP_TIMER_DIR="$(realpath -m -- "$STAGING_ROOT/timer")"
  SP_TTV_DIR="$(realpath -m -- "$STAGING_ROOT/harmonic")"
}

# Refuse before anything is written or stopped. MUSCAT_OBSLOG_DIR is the one
# the original incident wrote to, but all derived paths get the same check.
guard_staging_paths() {
  refuse_prod_path MUSCAT_DB_PATH "$SP_DB_PATH"
  refuse_prod_path MUSCAT_OBSLOG_DIR "$SP_OBSLOG_DIR"
  refuse_prod_path MUSCAT_PROSE_DIR "$SP_PROSE_DIR"
  refuse_prod_path MUSCAT_TIMER_DIR "$SP_TIMER_DIR"
  refuse_prod_path MUSCAT_TTV_DIR "$SP_TTV_DIR"
}

write_env() {
  local wt="$1" envfile="$1/.env"
  [ -r "$STAGING_ENV" ] || die "staging env $STAGING_ENV not readable"
  git -C "$wt" check-ignore -q .env || die "$wt/.env is not gitignored; refusing to write secrets there"
  if [ -e "$envfile" ] && ! head -1 "$envfile" | grep -qxF "$ENV_MARKER"; then
    die "$envfile exists and was not generated by this script; move it aside first"
  fi
  local tmp
  tmp="$(mktemp "$wt/.env.XXXXXX")"
  chmod 600 "$tmp"
  {
    echo "$ENV_MARKER"
    echo "# base: $STAGING_ENV"
    cat "$STAGING_ENV"
    echo
    echo "# --- dev overrides (python-dotenv: a later duplicate key wins) ---"
    echo "MUSCAT_DB_PATH=$SP_DB_PATH"
    echo "MUSCAT_OBSLOG_DIR=$SP_OBSLOG_DIR"
    echo "MUSCAT_PROSE_DIR=$SP_PROSE_DIR"
    echo "MUSCAT_TIMER_DIR=$SP_TIMER_DIR"
    echo "MUSCAT_TTV_DIR=$SP_TTV_DIR"
    # Defaults are <repo>/../ext_tools/*, which does not exist beside ~/temp.
    echo "MUSCAT_PROSE_PROJECT=$EXT_TOOLS/prose2"
    echo "MUSCAT_TIMER_PROJECT=$EXT_TOOLS/timer"
    echo "MUSCAT_HARMONIC_PROJECT=$EXT_TOOLS/harmonic"
    echo "MUSCAT_LCO_MONITOR_ENABLED=0"
    echo "MUSCAT_LCO_ALLOW_SUBMIT=0"
    echo "MUSCAT_MAX_FULL_JOBS=${DEV_MAX_FULL_JOBS:-0}"
    # Served directly on loopback with no nginx in front, so the staging
    # fail-closed auth would reject every request.
    echo "MUSCAT_REQUIRE_AUTH=0"
  } > "$tmp"
  mv "$tmp" "$envfile"
}

# A 200 from /healthz only proves *something* answers on the port. If another
# process grabbed it first, ours failed to bind and the browser would be
# talking to theirs, so check the listener is our server from this worktree.
verify_ours() {
  local wt pids pid owner
  wt="$(realpath "$1")"
  pids="$(listener_pids)"
  [ -n "$pids" ] || die "nothing listening on :$PORT after /healthz answered"
  for pid in $pids; do
    owner="$(muscat_server_of "$pid")" \
      || die "something other than muscat-db answers on :$PORT (pid $pid); not trusting it"
    [ "$(pid_uid "$owner")" = "$(id -u)" ] \
      || die "the server on :$PORT (pid $owner) belongs to another user; ours did not bind"
    [ "$(realpath "/proc/$owner/cwd")" = "$wt" ] \
      || die "the server on :$PORT (pid $owner) runs from $(readlink "/proc/$owner/cwd"), not $wt"
  done
}

# Every dev server runs in session muscatdb-dev, one window per port. Targets
# use tmux's `=` exact-match prefix: a bare name falls back to prefix matching,
# so `-t muscatdb-dev` could resolve to some other session such as
# muscatdb-dev-old, and respawn-pane -k would kill whatever runs there.
launch_in_tmux() {
  local wt="$1" launch="$2"
  if ! tmux has-session -t "=$TMUX_SESSION" 2>/dev/null; then
    tmux new-session -d -s "$TMUX_SESSION" -n "$TMUX_WINDOW" -c "$wt" "$launch"
  elif tmux list-windows -t "=$TMUX_SESSION" -F '#{window_name}' | grep -qxF "$TMUX_WINDOW"; then
    tmux respawn-pane -k -t "=$TMUX_SESSION:=$TMUX_WINDOW" -c "$wt" "$launch"
  else
    tmux new-window -d -t "=$TMUX_SESSION:" -n "$TMUX_WINDOW" -c "$wt" "$launch"
  fi
}

start() {
  local wt db launch uv
  wt="$(resolve_worktree "${1:-}")"
  resolve_staging_paths
  guard_staging_paths
  db="$SP_DB_PATH"
  [ -f "$db" ] || die "staging DB $db not found"
  uv="$(find_uv)"
  for tool in prose2 timer harmonic; do
    [ -d "$EXT_TOOLS/$tool" ] || echo "dev-server: warning: $EXT_TOOLS/$tool missing" >&2
  done

  link_data_files "$wt"
  write_env "$wt"
  stop_server

  launch="cd $(printf %q "$wt") && $(printf %q "$uv") run muscat-db serve"
  launch+=" --db $(printf %q "$db") --host $(printf %q "$HOST") --port $PORT --reload"
  launch+="; echo; echo '[dev server exited -- press enter]'; read -r _"
  launch_in_tmux "$wt" "$launch"

  echo "starting $(git -C "$wt" branch --show-current || true) from $wt on $HOST:$PORT (tmux: $TMUX_SESSION:$TMUX_WINDOW)"
  local deadline=$((SECONDS + HEALTH_TIMEOUT_S))
  until curl -fsS -m 5 -o /dev/null "http://127.0.0.1:$PORT/healthz" 2>/dev/null; do
    [ "$SECONDS" -lt "$deadline" ] || die "no /healthz after ${HEALTH_TIMEOUT_S}s; see: tmux attach -t $TMUX_SESSION:$TMUX_WINDOW"
    sleep 2
  done
  verify_ours "$wt"
  echo "up: http://$HOST:$PORT  (db: $db)"
  echo "note: --reload watches .py only; rerun start after template/JS edits"
}

COMMAND="${1:-}"
[ $# -gt 0 ] && shift
WORKTREE=""
while [ $# -gt 0 ]; do
  case "$1" in
    -p|--port)
      [ $# -ge 2 ] || die "$1 needs a value"
      PORT="$2"; shift 2 ;;
    --port=*) PORT="${1#--port=}"; shift ;;
    -h|--help) usage ;;
    -*) die "unknown option $1" ;;
    *)
      [ "$COMMAND" = start ] && [ -z "$WORKTREE" ] || usage
      WORKTREE="$1"; shift ;;
  esac
done

[[ "$PORT" =~ ^[0-9]+$ ]] && [ "$PORT" -ge 1024 ] && [ "$PORT" -le 65535 ] \
  || die "--port must be an integer in 1024-65535, got '$PORT'"
for reserved in $RESERVED_PORTS; do
  [ "$PORT" -ne "$reserved" ] || die "port $PORT belongs to production/staging; pick another"
done
# Auth is off (see the header), so a non-loopback bind would serve the data to
# the whole network with no login. Reach a remote host over an SSH tunnel.
case "$HOST" in
  127.0.0.1|::1|localhost) ;;
  *) die "DEV_HOST=$HOST refused: the dev server runs without auth, so it binds loopback only; use ssh -L $PORT:127.0.0.1:$PORT <host>" ;;
esac
TMUX_SESSION=muscatdb-dev
# Not the bare port: tmux reads a numeric window target as an index first.
TMUX_WINDOW="port-$PORT"

case "$COMMAND" in
  start)  start "$WORKTREE" ;;
  stop)   stop_server ;;
  status) status ;;
  *)      usage ;;
esac
