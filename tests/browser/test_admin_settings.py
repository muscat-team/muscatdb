"""Exercise account and access management through the settings card."""
from playwright.sync_api import expect


def test_admin_account_and_access_forms(page):
    page.goto('/settings')
    card = page.locator('#admin-dashboard')
    expect(card.locator('#admin-message')).to_have_text('Administration loaded.')
    expect(page.locator('.settings-section').first).to_have_attribute('id', 'admin-dashboard')
    page.fill('#admin-username', 'collaborator')
    page.fill('#admin-email', 'collaborator@univ.edu')
    page.get_by_role('button', name='Save email mapping').click()
    expect(card.locator('#admin-users')).to_contain_text('collaborator@univ.edu')
    page.fill('#admin-group-name', 'science-team')
    page.get_by_role('button', name='Create group', exact=True).click()
    expect(page.locator('#admin-member-group')).to_contain_text('science-team')
    page.select_option('#admin-member', 'collaborator')
    page.select_option('#admin-member-group', 'science-team')
    page.get_by_role('button', name='Add member', exact=True).click()
    expect(page.locator('#admin-memberships')).to_contain_text('science-team: collaborator')
    page.select_option('#admin-grant-group', 'science-team')
    page.fill('#admin-target', 'TOI-123')
    page.get_by_role('button', name='Add grant', exact=True).click()
    grant = page.locator('#admin-grants tbody tr').filter(has_text='science-team')
    expect(grant).to_contain_text('TOI-123')
    grant.get_by_role('button', name='Revoke').click()
    page.click('#message-modal-cancel')
    expect(grant).to_have_count(1)
    grant.get_by_role('button', name='Revoke').click()
    page.click('#message-modal-ok')
    expect(grant).to_have_count(0)
    page.select_option('#admin-clear-user', 'collaborator')
    page.get_by_role('button', name='Clear Cloudflare email').click()
    page.click('#message-modal-ok')
    expect(card.locator('#admin-users')).not_to_contain_text('collaborator@univ.edu')
    page.reload()
    expect(card.locator('#admin-users')).to_contain_text('collaborator')
    page.select_option('#admin-account', 'collaborator')
    page.select_option('#admin-scope', 'false')
    page.get_by_role('button', name='Save access scope').click()
    page.click('#message-modal-ok')
    account = page.locator('#admin-users tbody tr').filter(has_text='collaborator')
    expect(account).to_contain_text('Includes everyone')
    page.select_option('#admin-member', 'collaborator')
    page.select_option('#admin-member-group', 'science-team')
    page.get_by_role('button', name='Remove member', exact=True).click()
    page.click('#message-modal-ok')
    expect(page.locator('#admin-memberships')).to_contain_text('science-team: No members')
    page.get_by_role('button', name='Refresh', exact=True).click()
    expect(page.locator('#admin-message')).to_have_text('Updated.')
    heading = card.locator('h3')
    heading.focus()
    page.keyboard.press('Enter')
    expect(heading).to_have_attribute('aria-expanded', 'false')
    page.keyboard.press('Space')
    expect(heading).to_have_attribute('aria-expanded', 'true')


def test_nonadmin_has_no_dashboard(page, live_server):
    from tests.browser.conftest import PROXY_SECRET
    live_server.sql("INSERT OR IGNORE INTO users(username) VALUES ('ordinary')")
    page.context.set_extra_http_headers({'X-Forwarded-User': 'ordinary', 'X-MuSCAT-Proxy-Secret': PROXY_SECRET})
    page.goto('/settings')
    expect(page.locator('#admin-dashboard')).to_have_count(0)
